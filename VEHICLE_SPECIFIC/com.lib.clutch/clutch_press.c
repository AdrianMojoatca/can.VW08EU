void  clutch_press( void )
{
    TRACE("\n\r[CLUTCH_PRESS enter active=%d]\n\r", (int)clutch_active);
    if( clutch_active == FALSE ) return;



	CLUTCH_PWM_CUT( TRUE ); //cut the PWM line
    CLUTCH_PWM_OUT( TRUE );
	
	    

    __disable_fiq() ; 
    {        
        clutch_value = CLUTCH_PWM_RELEASE ; 
        
        tmr_dis( clutch_tmr ) ;
        
        tmr_update( clutch_tmr , CLUTCH_PWM_PERIOD - CLUTCH_PWM_RELEASE , FALSE ) ; 

        tmr_ena( clutch_tmr ); 
        
        clutch_on = TRUE ;        
    }
    __enable_fiq();

    os_tsk_wait( CLUTCH_PRESS_STEP_MS );
    
    clutch_update( CLUTCH_PWM_FULL_PRESS );

    TRACE("\n\r[CLUTCH_PRESS sensor a+b]\n\r");
    CLUTCH_SENSOR (TRUE); //activate the sensor
    
    os_tsk_wait( CLUTCH_PRESS_STEP_MS ); 
}
    
