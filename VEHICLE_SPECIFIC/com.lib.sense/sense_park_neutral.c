// byte 5
// 0x05 = park
// 0x06 = Reverse
// 0x07 = neutral
// 0x08 = Drive

//--------------------------------------------------------------------------//

void sense_park_3DC( Can_Msg *can_msg )
{
	if( DATA[5] == 0x05 ) // park
	{
		sense_rs_neutral_can( TRUE );
	}
	else
	{
		sense_rs_neutral_can( FALSE );
	}
}

