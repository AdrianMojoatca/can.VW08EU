void func_rap_start( void  )
{
    func_can_wake_enter();
    
    can_sync_loop (FUNC_CAN_DEV ,(Can_Sync_Func)rap_3D0,(Can_Sync_Arg)NULL,0x3D0 ,0 );
    
    TRACE_FUNC("\n\r[rap_START]\n\r");
}

/*--------------------------------------------------------------------------*/

Boolean func_rap_exec( void )
{    
    return FALSE  ; 	
}

/*--------------------------------------------------------------------------*/

void func_rap_stop( void )
{
    func_can_wake_leave();	

    can_sync_remove(FUNC_CAN_DEV , rap_3D0); 
    
    TRACE_FUNC("\n\r[RAP_STOP]\n\r");
}

/*--------------------------------------------------------------------------*/

Can_Sync_Flags rap_3D0( Can_Msg *can_msg )
{            
    can_msg->data._8_[0] |= 0x01 ;
       
    return  CAN_SYNC_TX ; 
}

