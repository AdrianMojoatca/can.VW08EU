/*==========================================================================*/
/*                  F U N C T I O N   P R O T O T Y P E S                   */
/*==========================================================================*/
static Can_Per_Flags can_wake_tx( Can_Msg *can_msg );
/*==========================================================================*/
/*                            V A R I A B L E S                             */
/*==========================================================================*/
static UInt8 wake_counter = 0 ; 
/*==========================================================================*/
/*                 F U N C T I O N   D E F I N I T I O N S                  */
/*==========================================================================*/

//--------------------------------------------------------------------------//

void func_can_wake_enter( void )
{
    if( !wake_counter )
    {
        can_per_loop( (Can_Per_Func)can_wake_tx , (Can_Per_Arg)NULL , 0 ,  20 );
    }

    ATOMIC( wake_counter ++ ); 
        	
}

//--------------------------------------------------------------------------//

void func_can_wake_leave( void )
{
    ATOMIC( wake_counter -- );
    
    if( !wake_counter )
    {
        can_per_remove( can_wake_tx ) ;
    }	
}

//--------------------------------------------------------------------------//

Can_Per_Flags can_wake_tx( Can_Msg *can_msg )
{
    *can_msg = func_can_table[ FUNC_CAN_WAKE ] ;         

    return FUNC_CAN_PER ;
}

