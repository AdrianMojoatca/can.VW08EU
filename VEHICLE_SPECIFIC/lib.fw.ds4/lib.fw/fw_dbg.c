void fw_dbg( int cmd )
{
	switch(cmd)
    {
        case 'l' : cmd_q_insert(INPUT_LOCK1      |INPUT_ON,0);break;
        case 'u' : cmd_q_insert(INPUT_UNLOCK_ALL1|INPUT_ON,0);break;
        case 't' : cmd_q_insert(INPUT_TRUNK      |INPUT_ON,0);break;
        
        case '1' : cmd_q_insert(INPUT_GWR        |INPUT_ON,0);break;
        case '2' : cmd_q_insert(INPUT_RS_ACCESSORY|INPUT_ON,0);break;
        case '3' : cmd_q_insert(INPUT_RS_IGNITION|INPUT_ON,0);break;
        case '4' : cmd_q_insert(INPUT_RS_STARTER |INPUT_ON,0);break;
        
        case '5' : cmd_q_insert(INPUT_RS_STARTER          ,0);break;
        case '6' : cmd_q_insert(INPUT_RS_IGNITION         ,0);break;
        case '7' : cmd_q_insert(INPUT_RS_ACCESSORY        ,0);break;
        case '8' : cmd_q_insert(INPUT_GWR                 ,0);break;
        
        case '9' : cmd_q_insert(INPUT_PARKING_ON          ,0);break;
        case '0' : cmd_q_insert(INPUT_PARKING_OFF         ,0);break;
        
        
        
        default : break;
    }
}

